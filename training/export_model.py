"""Bake a trained picker into the C++ build.

    .venv/bin/python export_model.py [checkpoint.pt]

Writes ../source/dsp/PickerWeights.h/.cpp (the weights as constant arrays) and ../tests/picker_reference.h: a few hops of
input features and the logits PyTorch produces for them, so the C++ forward pass can be checked against it.
"""
import sys
from pathlib import Path

import numpy as np
import torch

from train import MODELS, Picker, N_CLASSES, load_split

DSP = Path(__file__).parent.parent / "source" / "dsp"
TESTS = Path(__file__).parent.parent / "tests"


def lit(v):
    s = f"{v:.9g}"
    if all(c in "-0123456789" for c in s):  # "0f" is not a C++ literal; "0.0f" is
        s += ".0"
    return s + "f"


def arr(name, a):
    flat = np.asarray(a, np.float32).ravel()
    body = ",\n".join(", ".join(lit(v) for v in flat[i:i + 8]) for i in range(0, len(flat), 8))
    return f"const float {name}[{len(flat)}] = {{\n{body}\n}};\n\n"


def main():
    path = Path(sys.argv[1]) if len(sys.argv) > 1 else MODELS / "picker.pt"
    ck = torch.load(path, map_location="cpu")
    hidden = ck["hidden"]
    sd = ck["model"]
    model = Picker(dim=ck.get("dim", 385), hidden=hidden)
    model.load_state_dict(sd)
    model.eval()
    emb = sd["inp.0.weight"].shape[0]
    dim = sd["inp.0.weight"].shape[1]

    g = lambda k: sd[k].cpu().numpy()
    (DSP / "PickerWeights.h").write_text(f"""// Generated by training/export_model.py from {path.name}. Do not edit.
#pragma once

namespace nota
{{
constexpr int kPickerIn = {dim};
constexpr int kPickerEmb = {emb};
constexpr int kPickerHidden = {hidden};
constexpr int kPickerOut = {N_CLASSES};

extern const float kPickerWInp[];  // [emb][in]
extern const float kPickerBInp[];
extern const float kPickerWIh[];   // [3 hidden][emb]   (r, z, n)
extern const float kPickerWHh[];   // [3 hidden][hidden]
extern const float kPickerBIh[];
extern const float kPickerBHh[];
extern const float kPickerWOut[];  // [out][hidden + emb]
extern const float kPickerBOut[];
}} // namespace nota
""")
    body = "// Generated by training/export_model.py. Do not edit.\n#include \"PickerWeights.h\"\n\nnamespace nota\n{\n\n"
    body += arr("kPickerWInp", g("inp.0.weight")) + arr("kPickerBInp", g("inp.0.bias"))
    body += arr("kPickerWIh", g("gru.weight_ih_l0")) + arr("kPickerWHh", g("gru.weight_hh_l0"))
    body += arr("kPickerBIh", g("gru.bias_ih_l0")) + arr("kPickerBHh", g("gru.bias_hh_l0"))
    body += arr("kPickerWOut", g("head.weight")) + arr("kPickerBOut", g("head.bias"))
    body += "} // namespace nota\n"
    (DSP / "PickerWeights.cpp").write_text(body)

    # Reference vectors: a run of real feature frames (int8-exact) and the logits PyTorch gives for them.
    f = next(f for f in load_split("val") if len(f["feat"]) > 400)
    x = f["feat"][200:260].astype(np.float32) / 127.0
    with torch.no_grad():
        logits, _ = model(torch.from_numpy(x)[None])
    logits = logits[0].numpy()
    (TESTS / "picker_reference.h").write_text(
        "// Generated by training/export_model.py: input features and PyTorch's logits for them.\n#pragma once\n\n"
        f"constexpr int kRefHops = {len(x)};\n" + arr("kRefInput", x).replace("const float", "inline const float") +
        arr("kRefLogits", logits).replace("const float", "inline const float"))
    print(f"exported {path.name}: in {dim}, emb {emb}, hidden {hidden}; {sum(v.numel() for v in sd.values()):,} weights")


if __name__ == "__main__":
    main()
