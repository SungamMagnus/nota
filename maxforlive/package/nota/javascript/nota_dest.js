var NAMES = ["C", "C#", "D", "D#", "E", "F", "F#", "G", "G#", "A", "A#", "B"];
var PREF = [0, 4, 3, 5, 1, 2, 6]; // which scale degree a chord is built on, in order of preference: I V IV vi ii iii vii

var P = { mode: 0, lock: 0, key: 0, scale: 0, size: 0, role: 0, melody: 1, open: 0, octave: 0, chordvel: 80, dynamic: 0, humanize: 0, humamount: 25, voices: 16 };
var F = { on: 0, notes: 4, delay: 0, time: 800, decay: 70, spread: 4, length: 160, vel: 70 };
var live = { root: 0, iv: [0, 2, 4, 5, 7, 9, 11], name: "Major", mode: 1, have: false };
var active = {};              // channel * 128 + note  ->  { ch: c, notes: [n, ...] }  (what is sounding for that input note)
var shown = { name: "--", vel: "", chord: "", extra: "" };

// fixed behaviour constants
var FLOURISH_FLOOR = 60;   // flourish notes are strictly above this (C3 in Ableton's naming)
var DYN_TYPE = 0.33;       // dynamic mode: chance per note of a different chord type ...
var DYN_OCT = 0.15;        // ... of the chord moving one octave up or down ...
var DYN_ROLE = 0.15;       // ... of a different role
// humanize at the default amount (25%); the amount scales all of these linearly, so 100% is four times as much
var HUM_VEL = 0.08;        // velocity +-8% (plus +-3)
var HUM_ON_MS = 22;        // chord notes start up to this late
var HUM_OFF_MS = 28;       // and end up to this late
var HUM_FLOURISH_MS = 12;  // flourish notes move by up to +-this, and their length by +-15%
var SIZE_NAMES = ["triad", "7th", "9th"], ROLE_NAMES = ["smart", "root", "top"];
var lastEff = null;        // the chord settings used for the latest note (for the display and tests)

// time and randomness, replaceable so tests can drive them
var clock = function () { return new Date().getTime(); };
var rnd = function () { return Math.random(); };

// ---------------------------------------------------------------------------------------------------------------
function noteName(n) { return NAMES[((n % 12) + 12) % 12] + (Math.floor(n / 12) - 2); } // Ableton: MIDI 60 = C3

function cleanIntervals(a)
{
    var seen = {}, out = [], i;
    for (i = 0; i < a.length; i++)
    {
        var v = Math.round(Number(a[i]));
        if (isNaN(v)) continue;
        v = ((v % 12) + 12) % 12;
        if (!seen[v]) { seen[v] = 1; out.push(v); }
    }
    out.sort(function (x, y) { return x - y; });
    return out.length >= 5 ? out : [0, 2, 4, 5, 7, 9, 11];
}

function norm(s) { return String(s).toLowerCase().replace(/[^a-z0-9#]/g, ""); }

function findScale(name)
{
    var n = norm(name), i;
    for (i = 0; i < SCALES.length; i++) if (norm(SCALES[i][0]) === n) return i;
    return -1;
}

// Locked to Live only when Live has told us its scale (it does not on Live 11).
// P.lock is the scale mode: 0 Chromatic (the played note is left alone), 1 Internal (snapped to the Key / Scale menus),
// 2 Live (snapped to Live's global scale, which the menus then show). The menus always give the scale for chords and flourish
// unless Live is followed.
function followsLive() { return P.lock === 2 && live.have; }
function snapsNotes() { return P.lock >= 1; }

function currentScale()
{
    if (followsLive())
        return { root: live.root, iv: live.iv, label: NAMES[live.root] + " " + live.name + " (Live)" };
    var s = SCALES[Math.max(0, Math.min(P.scale, SCALES.length - 1))];
    return { root: P.key, iv: s[1], label: NAMES[P.key] + " " + s[0] };
}

function hint()
{
    if (P.lock === 2 && !live.have) return "no Live scale: using menus";
    if (followsLive() && !live.mode) return "Live scale mode is off";
    if (followsLive()) return "locked to Live";
    if (P.lock === 1) return "snapped to scale";
    return "";
}

// Keep the Key / Scale menus in step: while locked they show Live's scale (and are greyed out); otherwise they are live.
function syncMenus()
{
    var locked = followsLive();
    outlet(4, locked ? 0 : 1);
    if (locked)
    {
        P.key = live.root;
        outlet(2, P.key);
        var si = findScale(live.name);
        if (si >= 0) { P.scale = si; outlet(3, si); }
    }
}

// Scale note number `idx` (any integer; 0 = the root, n = the root an octave up) for scale sc.
function scaleNote(sc, idx)
{
    var n = sc.iv.length;
    var o = Math.floor(idx / n);
    return sc.root + 12 * o + sc.iv[idx - o * n];
}

// The scale index whose pitch is nearest to MIDI note m (ties go down).
function nearestIdx(sc, m)
{
    var n = sc.iv.length;
    var o = Math.floor((m - sc.root) / 12);
    var best = 0, bd = 1e9, i;
    for (i = (o - 1) * n; i <= (o + 2) * n; i++)
    {
        var d = Math.abs(scaleNote(sc, i) - m);
        if (d < bd) { bd = d; best = i; }
    }
    return best;
}

// Chord for the input note m; `base` is the pitch the note itself will play (snapped when locked).
// Returns the chord pitches (the note itself is not in the list when it would double `base`).
//   role 0 Smart: a diatonic chord that contains the note's scale degree, placed under the note
//   role 1 Root : the note is the chord's root (bass); the other tones are stacked in thirds above it
//   role 2 Top  : the note is the chord's top voice; tones are stacked in thirds below it
function chordFor(sc, m, eff)
{
    var n = sc.iv.length;
    var idx = nearestIdx(sc, m);
    var count = 3 + eff.size;
    var notes = [], k;

    if (eff.role === 1)
    {
        for (k = (P.melody ? 1 : 0); k < count; k++) notes.push(scaleNote(sc, idx + 2 * k));
    }
    else if (eff.role === 2)
    {
        for (k = 1; k < count; k++) notes.push(scaleNote(sc, idx - 2 * k));
    }
    else
    {
        var d0 = ((idx % n) + n) % n;
        var order = [], i;
        for (i = 0; i < PREF.length; i++) if (PREF[i] < n) order.push(PREF[i]);
        for (i = 7; i < n; i++) order.push(i);
        var tones = [d0];
        for (i = 0; i < order.length; i++)
        {
            var t = [];
            for (k = 0; k < count; k++) t.push((order[i] + 2 * k) % n);
            if (t.indexOf(d0) >= 0) { tones = t; break; }
        }
        var seen = {};
        for (i = 0; i < tones.length; i++)
        {
            var deg = tones[i];
            if (seen[deg]) continue;
            seen[deg] = 1;
            if (deg === d0 && P.melody) continue;           // the melody note already is this tone
            var below = (((idx - deg) % n) + n) % n;        // steps down to the nearest lower occurrence of this degree
            if (below === 0) below = n;
            notes.push(scaleNote(sc, idx - below));
        }
    }

    notes.sort(function (a, b) { return a - b; });
    if (P.open && notes.length >= 3) notes[notes.length - 2] -= 12;   // open voicing: drop the second voice from the top

    var out = [], used = {};
    for (k = 0; k < notes.length; k++)
    {
        var p = notes[k] + 12 * eff.octave;
        if (p < 0 || p > 127 || used[p]) continue;
        used[p] = 1;
        out.push(p);
    }
    out.sort(function (a, b) { return a - b; });
    return out;
}

// ---------------------------------------------------------------------------------------------------------------
// OUTPUT. Every note we sound is an "instance" with an id. own[] remembers which instance is sounding each pitch, so a
// late note-off never cuts a newer note on the same pitch. Notes that start or end later (humanize, flourish) go
// through one queue, fq, drained by a short timer that only runs while the queue is not empty.
var own = {};         // channel * 128 + pitch  ->  id of the instance sounding
var fq = [];          // scheduled events {t, kind: "on"|"off", ch, n, v, id, soft}   soft: skip if the pitch is already sounding
var nid = 0;
var ticker = null;

function send(status, a, b, len)
{
    if (len === 2) outlet(0, status, a);
    else outlet(0, status, a, b);
}

function display(name, vel, chord, extra)
{
    shown.name = name; shown.vel = vel; shown.chord = chord; shown.extra = extra || "";
    outlet(1, name, vel, chord, currentScale().label, shown.extra || hint());
}

function startTicker()
{
    if (ticker) return;
    ticker = new Task(tick, this);
    ticker.interval = 5;
    ticker.repeat();
}

function stopTicker()
{
    if (!ticker) return;
    ticker.cancel();
    ticker = null;
}

function emitOn(ch, n, v, id)
{
    send(0x90 | ch, n, v, 3);
    own[ch * 128 + n] = id;
}

function emitOff(ch, n, id)
{
    var k = ch * 128 + n;
    if (own[k] !== id) return;      // a newer note took this pitch over: leave it alone
    send(0x80 | ch, n, 0, 3);
    delete own[k];
}

function schedule(ev)
{
    fq.push(ev);
    fq.sort(function (a, b) { return a.t - b.t || (a.kind === "off" ? -1 : 1); });
    startTicker();
}

function removePendingOn(id)
{
    for (var i = 0; i < fq.length; i++)
        if (fq[i].kind === "on" && fq[i].id === id) { fq.splice(i, 1); return true; }
    return false;
}

// Start a note now, or after delayMs. Returns its instance id.
function startNote(ch, n, v, delayMs, soft)
{
    var id = ++nid;
    if (delayMs <= 0)
    {
        if (!(soft && own[ch * 128 + n] !== undefined)) emitOn(ch, n, v, id);
    }
    else
        schedule({ t: clock() + delayMs, kind: "on", ch: ch, n: n, v: v, id: id, soft: !!soft });
    return id;
}

function endNote(ch, n, id, delayMs)
{
    if (removePendingOn(id)) return;   // it had not started yet: it never will
    if (delayMs <= 0) emitOff(ch, n, id);
    else schedule({ t: clock() + delayMs, kind: "off", ch: ch, n: n, v: 0, id: id });
}

function tick()
{
    var now = clock();
    while (fq.length && fq[0].t <= now)
    {
        var e = fq.shift();
        if (e.kind === "on")
        {
            if (e.soft && (own[e.ch * 128 + e.n] !== undefined || voiceCount() >= P.voices)) continue;   // already sounding, or no voice free
            emitOn(e.ch, e.n, e.v, e.id);
        }
        else
            emitOff(e.ch, e.n, e.id);
    }
    if (!fq.length) stopTicker();
}

// --- humanize: subtle, and never on the played note itself
function hk() { return P.humanize ? P.humamount / 25 : 0; }   // 1 at the default amount, 0 when off
function hv(v)
{
    var k = hk();
    if (!k) return v;
    var x = v * (1 + (rnd() - 0.5) * 2 * HUM_VEL * k) + (rnd() - 0.5) * 6 * k;
    return Math.max(1, Math.min(127, Math.round(x)));
}
function hOnDelay() { return rnd() * HUM_ON_MS * hk(); }
function hOffDelay() { return rnd() * HUM_OFF_MS * hk(); }

// --- dynamic mode: per note, sometimes a different chord type / octave / role
function otherOf(v, n) { var r = Math.floor(rnd() * (n - 1)); return r >= v ? r + 1 : r; }

function effectiveSettings()
{
    var eff = { size: P.size, role: P.role, octave: P.octave, text: "" }, parts = [];
    if (P.dynamic && P.mode === 1)
    {
        if (rnd() < DYN_TYPE) { eff.size = otherOf(P.size, 3); parts.push(SIZE_NAMES[eff.size]); }
        if (rnd() < DYN_OCT) { var d = rnd() < 0.5 ? -1 : 1; eff.octave = P.octave + d; parts.push("oct " + (d > 0 ? "+1" : "-1")); }
        if (rnd() < DYN_ROLE) { eff.role = otherOf(P.role, 3); parts.push(ROLE_NAMES[eff.role]); }
    }
    eff.text = parts.join(", ");
    lastEff = eff;
    return eff;
}

// --- voice count: the most notes the device lets sound at once (melody, chord and flourish together)
function voiceCount()
{
    var n = 0, k, i;
    for (k in own) n++;
    for (i = 0; i < fq.length; i++)
        if (fq[i].kind === "on" && !fq[i].soft) n++;   // chord notes still waiting for their humanized start
    return n;
}

// Free one voice: end the one that has been sounding longest (or drop the earliest chord note still waiting to start).
function stealOldest()
{
    var best = -1, bestKey = null, bestAt = -1, k, i;
    for (k in own)
        if (best < 0 || own[k] < best) { best = own[k]; bestKey = k; }
    for (i = 0; i < fq.length; i++)
        if (fq[i].kind === "on" && !fq[i].soft && (best < 0 || fq[i].id < best)) { best = fq[i].id; bestAt = i; bestKey = null; }
    if (best < 0) return false;
    if (bestKey !== null)
    {
        send(0x80 | (Math.floor(bestKey / 128) | 0), (bestKey % 128) | 0, 0, 3);
        delete own[bestKey];
    }
    else
        fq.splice(bestAt, 1);
    return true;
}

function releaseKey(key)
{
    var a = active[key];
    if (!a) return;
    for (var i = 0; i < a.notes.length; i++)
        endNote(a.ch, a.notes[i].n, a.notes[i].id, a.notes[i].human ? hOffDelay() : 0);
    delete active[key];
}

function noteOn(ch, note, vel)
{
    var key = ch * 128 + note;
    releaseKey(key); // a re-trigger of the same note: end the old one first
    flourishOff();   // a new trigger restarts the flourish: the previous one's pending notes are dropped

    var sc = currentScale();
    var base = snapsNotes() ? scaleNote(sc, nearestIdx(sc, note)) : note;   // Internal / Live: the note is moved onto the scale
    var eff = effectiveSettings();
    var notes = [], i;

    // what we would like to play: the played note, then the chord
    var wantBase = (P.mode !== 1 || P.melody);
    var chordNotes = [];
    if (P.mode === 1)
    {
        var chord = chordFor(sc, note, eff);
        for (i = 0; i < chord.length; i++)
            if (!(P.melody && chord[i] === base)) chordNotes.push(chord[i]);
    }

    // Voice Count: the played note comes first, then the chord tones nearest to it (ties: the lower one); older notes make room
    var room = Math.max(0, P.voices - (wantBase ? 1 : 0));
    if (chordNotes.length > room)
    {
        var keep = chordNotes.slice().sort(function (a, b) { return Math.abs(a - base) - Math.abs(b - base) || a - b; }).slice(0, room);
        chordNotes = chordNotes.filter(function (n) { return keep.indexOf(n) >= 0; });
    }
    var need = (wantBase ? 1 : 0) + chordNotes.length;
    while (voiceCount() + need > P.voices && stealOldest()) { }

    // the played note itself: immediate and untouched by humanize
    if (wantBase) notes.push({ n: base, id: startNote(ch, base, vel, 0, false), human: false });
    var cv = Math.max(1, Math.min(127, Math.round(vel * P.chordvel / 100)));
    for (i = 0; i < chordNotes.length; i++)
        notes.push({ n: chordNotes[i], id: startNote(ch, chordNotes[i], hv(cv), hOnDelay(), false), human: true });

    active[key] = { ch: ch, notes: notes };
    var pitches = [];
    for (i = 0; i < notes.length; i++) pitches.push(notes[i].n);
    var sorted = pitches.slice().sort(function (a, b) { return a - b; });
    var text = "";
    for (i = 0; i < sorted.length; i++) text += (i ? " " : "") + noteName(sorted[i]);
    display(noteName(note), "vel " + vel + "  ch " + (ch + 1), P.mode === 1 ? text : "", eff.text);

    triggerFlourish(ch, pitches.length ? pitches : [base], vel, base);
}

function noteOff(ch, note)
{
    var key = ch * 128 + note;
    if (active[key])
    {
        releaseKey(key);
        var any = false, k;
        for (k in active) { any = true; break; }
        if (!any) display("--", "", "", "");
    }
    else
        send(0x80 | ch, note, 0, 3); // a note we never started: pass the note-off through
}

// ---------------------------------------------------------------------------------------------------------------
// FLOURISH: every note-on schedules F.notes random scale notes, starting F.delay ms after the note and spread over a
// window of F.time ms (a random delay line), each F.length
// long, getting quieter by F.decay per step. They are random scale notes within F.spread scale steps of the notes that
// were just played, always above C3 and above the played note when that is higher. They do not depend on the note
// being held.
function pickOffset(spread)
{
    // closer scale steps are likelier: weight 1/m
    var total = 0, m;
    for (m = 1; m <= spread; m++) total += 1 / m;
    var r = rnd() * total;
    for (m = 1; m <= spread; m++)
    {
        r -= 1 / m;
        if (r <= 0) break;
    }
    if (m > spread) m = spread;
    return (rnd() < 0.5 ? -1 : 1) * m;
}

function flourishPitch(sc, refNotes, floor)
{
    var tries, p;
    for (tries = 0; tries < 8; tries++)
    {
        var ref = refNotes[Math.floor(rnd() * refNotes.length) % refNotes.length];
        while (ref <= floor) ref += 12;     // lift the reference into the register above the floor (same pitch class)
        p = scaleNote(sc, nearestIdx(sc, ref) + pickOffset(F.spread));
        if (p > floor && p <= 127 && refNotes.indexOf(p) < 0) return p;
    }
    // fallback: one of the first scale notes above the floor
    var i = nearestIdx(sc, floor) - sc.iv.length;
    while (scaleNote(sc, i) <= floor) i++;
    p = scaleNote(sc, i + Math.floor(rnd() * F.spread));
    return (p <= 127 && refNotes.indexOf(p) < 0) ? p : -1;
}

function triggerFlourish(ch, refNotes, vel, base)
{
    if (!F.on || F.notes < 1) return;
    var sc = currentScale();
    var floor = Math.max(FLOURISH_FLOOR, base);
    var now = clock();
    var times = [], i;
    for (i = 0; i < F.notes; i++)
    {
        var t = now + Math.max(30, F.delay) + rnd() * Math.max(0, F.time - 30);
        if (P.humanize) t += (rnd() - 0.5) * 2 * HUM_FLOURISH_MS * hk();
        times.push(Math.max(now + 10, t));
    }
    times.sort(function (a, b) { return a - b; });

    for (i = 0; i < times.length; i++)
    {
        var pitch = flourishPitch(sc, refNotes, floor);
        if (pitch < 0) continue;
        var v = Math.round(vel * (F.vel / 100) * Math.pow(F.decay / 100, i) * (0.85 + 0.3 * rnd()));
        v = hv(Math.max(1, Math.min(127, v)));
        var len = F.length * (P.humanize ? 1 + (rnd() - 0.5) * 0.3 * hk() : 1);
        var id = ++nid;
        schedule({ t: times[i], kind: "on", ch: ch, n: pitch, v: v, id: id, soft: true });
        schedule({ t: times[i] + len, kind: "off", ch: ch, n: pitch, v: 0, id: id });
    }
}

function flourishOff()
{
    // stops what has not happened yet; flourish notes already sounding are allowed to finish
    var gone = {};
    fq.forEach(function (e) { if (e.kind === "on" && e.soft) gone[e.id] = 1; });
    fq = fq.filter(function (e) { return !gone[e.id]; });
    if (!fq.length) stopTicker();
}

function midi(status, d1, d2, len)
{
    var type = status & 0xF0, ch = status & 0x0F;
    if (type === 0x90 && d2 > 0) noteOn(ch, d1, d2);
    else if (type === 0x80 || type === 0x90) noteOff(ch, d1);
    else send(status, d1, d2, len);   // pitch bend, CC, channel pressure (MPE expression, zone setup): pass through
}

function list()
{
    var a = arrayfromargs(arguments);
    if (a.length >= 2) midi(a[0], a[1], a.length > 2 ? a[2] : 0, a.length);
}

function panic()
