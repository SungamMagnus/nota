// Nóta destination: parses the MIDI that Nóta source sends, shows the note being received, and adds
//   * ACCOMPANY: a chord for every note, in the current key and scale
//   * FLOURISH : a delay-like burst of random scale notes after every note (independent of ACCOMPANY, and of the
//                note being held: the burst plays out after the note ends; both can be on together). Always above C3
//                (MIDI 60), and above the received note when that is higher.
//   * DYNAMIC  : per note, sometimes picks a different chord type (33%), octave +-1 (15%) or role (15%)
//   * HUMANIZE : subtle random timing and velocity on every chord and flourish note (not on the played note itself)
// Written in the ES5 subset Max's [js] object understands. NOTE: Max calls a global function of the same name as an
// incoming message directly, so no helper function may be named like a message (flourish, mode, key, scale, ...).
//
// Where the scale comes from:
//   SCALE LOCK on  -> Live's global scale (root_note / scale_intervals from the Live API). The Key and Scale menus
//                     show it (they are set from here) and are greyed out. The played note is moved to the nearest
//                     note of that scale.
//   SCALE LOCK off -> the Key and Scale menus choose. The played note is left alone.
//
//   inlet 0   list  status data1 [data2]      raw MIDI from [receive]
//             mode / lock / key / scale / size / role / melody / openvoicing / octave / chordvel / dynamic / humanize / humamount / voices  (controls)
//             flourish / flnotes / fldelay / fltime / fldecay / flspread / fllength / flvel                     (flourish)
//             liveroot / liveintervals / livename / livemode                                         (Live's global scale)
//             panic
//   outlet 0  list  status data1 [data2]      raw MIDI to [iter] -> [midiout]
//   outlet 1  five symbols for the display: note, velocity, chord, key/scale, hint
//   outlet 2  int   Key menu index    (use with [prepend set])
//   outlet 3  int   Scale menu index  (use with [prepend set])
//   outlet 4  int   1 = menus active, 0 = menus greyed out (following Live)  (use with [prepend active])
//
// Generated by make_devices.py: the scale table below is the same one the Scale menu uses (same order).

inlets = 1;
outlets = 5;

